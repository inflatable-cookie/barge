//! `barge init` and its local scratch file, on temporary repositories with a fake
//! volume identity. Nothing here touches a real home folder, a real drive or
//! this repository's own `AGENTS.md`; git runs only inside those fixtures.

// An integration test target is its own crate, and its fixture helpers are not
// inside a `#[test]` function, where `clippy.toml` grants the exception. Tests
// may unwrap, expect and panic; the shipped crates may not.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

mod common;

use std::fs;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};
use std::process::Command;

use barge::workflow::{END_MARKER, POINTER_LINE, START_MARKER};
use barge::{
    Absent, Barge, BindingKind, BindingState, BlockState, Class, ErrorKind, ExcludeState,
    InitAction, Placement, Prior, VolumeState,
};
use common::{snapshot, Fixture};

fn layout(fixture: &Fixture) {
    fixture
        .barge
        .set_layout(
            Class::Scratch,
            Placement {
                volume: "Builds".into(),
                path: "scratch".into(),
                absent: Absent::Fail,
            },
        )
        .unwrap();
}

/// A folder named `name` inside the fixture, with its scratch class folder. It
/// has no `.git`, so it is not a repository.
fn repository(fixture: &Fixture, name: &str) -> PathBuf {
    fs::create_dir_all(fixture.base().join("scratch")).unwrap();
    fixture.temp.folder(name).unwrap()
}

/// Run git in `dir` with a fixed identity and no inherited repository overrides.
fn git(dir: &Path, arguments: &[&str]) -> String {
    let output = Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(arguments)
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .env("GIT_AUTHOR_NAME", "Barge Test")
        .env("GIT_AUTHOR_EMAIL", "test@example.invalid")
        .env("GIT_COMMITTER_NAME", "Barge Test")
        .env("GIT_COMMITTER_EMAIL", "test@example.invalid")
        .output()
        .expect("run git");
    assert!(
        output.status.success(),
        "git {arguments:?}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8_lossy(&output.stdout).trim().to_string()
}

/// A repository with `git init` in a fixture folder.
fn git_repo(fixture: &Fixture, name: &str) -> PathBuf {
    let repo = repository(fixture, name);
    git(&repo, &["init", "--quiet", "-b", "main"]);
    repo
}

fn block_text(fixture: &Fixture, project: &str) -> String {
    fixture.barge.workflow(project).unwrap().text
}

fn local(repository: &Path) -> PathBuf {
    repository.join("AGENTS.local.md")
}

fn agents(repository: &Path) -> PathBuf {
    repository.join("AGENTS.md")
}

fn exclude_file(repository: &Path) -> PathBuf {
    repository.join(".git/info/exclude")
}

/// How many lines of the exclude file name the local file.
fn exclude_entries(repository: &Path) -> usize {
    fs::read_to_string(exclude_file(repository))
        .unwrap()
        .lines()
        .filter(|line| *line == "/AGENTS.local.md")
        .count()
}

#[test]
fn init_writes_the_local_file_and_excludes_it_from_git() {
    let fixture = Fixture::new();
    fixture.register();
    layout(&fixture);
    let repo = git_repo(&fixture, "repo");
    let block = block_text(&fixture, "repo");

    let report = fixture.barge.init(&repo, None).unwrap();
    assert_eq!(report.action, InitAction::Inserted);
    assert_eq!(report.project, "repo");
    assert_eq!(report.path, local(&repo));
    assert_eq!(report.exclude, ExcludeState::Excluded);
    assert_eq!(report.scratch, fixture.base().join("scratch/repo"));
    assert_eq!(report.volume_name, "Builds");
    assert_eq!(report.volume_state, VolumeState::Present);
    assert_eq!(fs::read_to_string(local(&repo)).unwrap(), block);

    // The file has no markers: barge owns it whole.
    let text = fs::read_to_string(local(&repo)).unwrap();
    assert!(text.starts_with("<!-- Generated by `barge init`"), "{text}");
    assert!(
        !text.contains(START_MARKER) && !text.contains(END_MARKER),
        "{text}"
    );
    assert!(
        text.contains(&format!("    {}\n", report.scratch.display())),
        "{text}"
    );
    assert!(
        text.contains("barge scratch new --volume Builds --project repo"),
        "{text}"
    );
    assert!(
        text.contains("Never write scratch to a home folder or a drive root"),
        "{text}"
    );
    assert!(
        !text.contains("worktree") && !text.contains("Worktree"),
        "worktrees are not mentioned until that class has a binding: {text}"
    );

    // The committed file is never created or edited, and the exclude entry lands.
    assert!(!agents(&repo).exists());
    assert_eq!(exclude_entries(&repo), 1);
    assert!(
        report.warnings.iter().any(|w| w.contains(POINTER_LINE)),
        "a missing pointer prints the line to add: {:?}",
        report.warnings
    );
    assert_eq!(git(&repo, &["status", "--porcelain"]), "");

    // A second run changes nothing: not the file, the exclude file or the bindings.
    let file = fs::read(local(&repo)).unwrap();
    let exclude = fs::read(exclude_file(&repo)).unwrap();
    let bindings = fs::read(fixture.barge.state_dir().join("bindings.json")).unwrap();
    let again = fixture.barge.init(&repo, None).unwrap();
    assert_eq!(again.action, InitAction::Unchanged);
    assert_eq!(again.exclude, ExcludeState::Excluded);
    assert_eq!(fs::read(local(&repo)).unwrap(), file);
    assert_eq!(fs::read(exclude_file(&repo)).unwrap(), exclude);
    assert_eq!(
        fs::read(fixture.barge.state_dir().join("bindings.json")).unwrap(),
        bindings,
        "an identical workflow binding is not rewritten"
    );
}

