#[test]
fn check_reports_current_stale_and_missing_and_writes_nothing() {
    let fixture = Fixture::new();
    fixture.register();
    layout(&fixture);
    let repo = git_repo(&fixture, "repo");
    let exclude_before = fs::read(exclude_file(&repo)).unwrap();

    let check = fixture.barge.init_check(&repo, None).unwrap();
    assert_eq!(check.state, BlockState::Missing);
    assert_eq!(check.exclude, ExcludeState::NotExcluded);
    assert!(!check.is_current());
    assert_eq!(check.path, local(&repo));
    assert_eq!(check.scratch, fixture.base().join("scratch/repo"));
    assert_eq!(
        check.diff[0],
        format!("--- {} (no file)", check.path.display())
    );
    assert_eq!(
        check.diff[1],
        format!("+++ {} (rendered file)", check.path.display())
    );
    assert!(
        check.diff[2..].iter().all(|line| line.starts_with('+')),
        "{:?}",
        check.diff
    );
    assert!(!local(&repo).exists(), "check writes nothing");
    assert_eq!(fs::read(exclude_file(&repo)).unwrap(), exclude_before);

    fixture.barge.init(&repo, None).unwrap();
    let check = fixture.barge.init_check(&repo, None).unwrap();
    assert_eq!(check.state, BlockState::Current);
    assert!(check.is_current());
    assert!(check.diff.is_empty());

    let text = fs::read_to_string(local(&repo)).unwrap();
    fs::write(
        local(&repo),
        text.replace("## Scratch for this project", "## Old scratch"),
    )
    .unwrap();
    let check = fixture.barge.init_check(&repo, None).unwrap();
    assert_eq!(check.state, BlockState::Stale);
    assert!(!check.is_current());
    assert_eq!(
        check.diff[0],
        format!("--- {} (current file)", check.path.display())
    );
    assert_eq!(
        check.diff[1],
        format!("+++ {} (rendered file)", check.path.display())
    );
    assert!(check.diff.iter().any(|line| line == "-## Old scratch"));
    assert!(check
        .diff
        .iter()
        .any(|line| line == "+## Scratch for this project"));
    assert!(check.diff.iter().any(|line| line.starts_with(' ')));
}

#[test]
fn a_current_file_outside_git_exclude_is_not_current() {
    let fixture = Fixture::new();
    fixture.register();
    layout(&fixture);
    let repo = git_repo(&fixture, "repo");
    fixture.barge.init(&repo, None).unwrap();

    // Someone removes the exclude entry: the file matches but Git would see it.
    fs::write(exclude_file(&repo), "# comments only\n").unwrap();
    let before = fs::read(exclude_file(&repo)).unwrap();
    let check = fixture.barge.init_check(&repo, None).unwrap();
    assert_eq!(check.state, BlockState::Current);
    assert_eq!(check.exclude, ExcludeState::NotExcluded);
    assert!(!check.is_current());
    assert!(check.warnings.iter().any(|w| w.contains("not excluded")));
    assert_eq!(
        fs::read(exclude_file(&repo)).unwrap(),
        before,
        "check writes nothing"
    );

    // `init` adds the entry back and the check passes.
    let report = fixture.barge.init(&repo, None).unwrap();
    assert_eq!(report.exclude, ExcludeState::Excluded);
    assert_eq!(exclude_entries(&repo), 1);
    assert!(fixture.barge.init_check(&repo, None).unwrap().is_current());
}

