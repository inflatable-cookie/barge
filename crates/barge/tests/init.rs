#[test]
fn a_linked_worktree_puts_the_exclude_entry_in_the_common_git_directory() {
    let fixture = Fixture::new();
    fixture.register();
    layout(&fixture);
    let repo = git_repo(&fixture, "repo");
    git(&repo, &["commit", "--quiet", "--allow-empty", "-m", "base"]);
    let tree = fixture.temp.child("tree");
    git(
        &repo,
        &[
            "worktree",
            "add",
            "--quiet",
            "-b",
            "feature",
            tree.to_str().unwrap(),
        ],
    );
    assert!(
        tree.join(".git").is_file(),
        "a linked worktree's .git is a file"
    );

    let report = fixture.barge.init(&tree, None).unwrap();
    assert_eq!(report.action, InitAction::Inserted);
    assert_eq!(report.exclude, ExcludeState::Excluded);
    assert_eq!(
        exclude_entries(&repo),
        1,
        "the main repository's info/exclude names the file"
    );
    assert_eq!(git(&tree, &["status", "--porcelain"]), "");
    assert!(fixture.barge.init_check(&tree, None).unwrap().is_current());
}

