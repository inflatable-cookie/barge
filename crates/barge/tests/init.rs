#[test]
fn init_records_a_workflow_binding_that_undo_can_forget() {
    let fixture = Fixture::new();
    fixture.register();
    layout(&fixture);
    let repo = repository(&fixture, "repo");
    fixture.barge.init(&repo, None).unwrap();

    let consumer = repo.to_string_lossy().into_owned();
    let record = fixture.barge.bindings().get(&consumer).unwrap().unwrap();
    assert_eq!(record.kind, BindingKind::Workflow);
    assert_eq!(record.class, Class::Scratch);
    assert_eq!(record.prior, Prior::InPlace);
    assert_eq!(record.owned_path(), local(&repo));
    assert_eq!(record.applied.value, fixture.base().join("scratch/repo"));
    assert_eq!(fixture.barge.bindings().list().unwrap().len(), 1);

    let file_contents = fs::read(local(&repo)).unwrap();
    let forgotten = fixture.barge.bindings().undo(&consumer).unwrap();
    assert_eq!(forgotten.kind, BindingKind::Workflow);
    assert_eq!(fs::read(local(&repo)).unwrap(), file_contents);
    assert!(fixture.barge.bindings().list().unwrap().is_empty());

    // The binding survives a reopen, so doctor can check it later.
    let reopened = Barge::open_with(
        fixture.barge.state_dir(),
        fixture.os.clone(),
        fixture.clock.clone(),
    )
    .unwrap();
    assert!(reopened.bindings().list().unwrap().is_empty());
}

#[test]
fn doctor_reports_the_local_file_as_ok_stale_and_missing() {
    let fixture = Fixture::new();
    fixture.register();
    layout(&fixture);
    let repo = repository(&fixture, "repo");
    fixture.barge.init(&repo, None).unwrap();

    let report = fixture.barge.doctor().unwrap();
    assert!(report.ok, "{report:?}");
    assert_eq!(report.problems(), 0);
    assert_eq!(report.binding_reports.len(), 1);
    assert_eq!(report.binding_reports[0].kind, BindingKind::Workflow);
    assert_eq!(report.binding_reports[0].path, local(&repo));
    assert_eq!(report.binding_reports[0].state, BindingState::Ok);

    // A file that no longer matches the layout is stale.
    let text = fs::read_to_string(local(&repo)).unwrap();
    fs::write(
        local(&repo),
        text.replace("## Scratch for this project", "## Scratch"),
    )
    .unwrap();
    let report = fixture.barge.doctor().unwrap();
    assert!(!report.ok);
    assert_eq!(report.problems(), 1);
    match &report.binding_reports[0].state {
        BindingState::Stale { reason } => assert!(reason.contains("stale"), "{reason}"),
        other => panic!("expected stale, got {other:?}"),
    }

    // No file at all is missing.
    fs::remove_file(local(&repo)).unwrap();
    let report = fixture.barge.doctor().unwrap();
    assert!(!report.ok);
    assert_eq!(report.binding_reports[0].state, BindingState::Missing);
}

#[test]
fn a_binding_that_still_names_agents_md_is_stale_until_init_reruns() {
    let fixture = Fixture::new();
    fixture.register();
    layout(&fixture);
    let repo = repository(&fixture, "repo");
    fixture.barge.init(&repo, None).unwrap();

    // Turn the record into the earlier shape: a workflow target with no `file`
    // field, which reads as the committed AGENTS.md.
    let path = fixture.barge.state_dir().join("bindings.json");
    let mut document: serde_json::Value =
        serde_json::from_slice(&fs::read(&path).unwrap()).unwrap();
    for record in document["bindings"].as_array_mut().unwrap() {
        if record["kind"] == "workflow" {
            record["target"].as_object_mut().unwrap().remove("file");
        }
    }
    fs::write(&path, serde_json::to_vec_pretty(&document).unwrap()).unwrap();

    let report = fixture.barge.doctor().unwrap();
    assert!(!report.ok);
    assert_eq!(report.binding_reports[0].path, agents(&repo));
    match &report.binding_reports[0].state {
        BindingState::Stale { reason } => {
            assert!(reason.contains("AGENTS.md"), "{reason}");
            assert!(reason.contains("rerun barge init"), "{reason}");
        }
        other => panic!("expected stale, got {other:?}"),
    }
    // Doctor only says so: nothing is rewritten.
    assert!(!agents(&repo).exists());

    fixture.barge.init(&repo, None).unwrap();
    let report = fixture.barge.doctor().unwrap();
    assert!(report.ok, "{report:?}");
    assert_eq!(report.binding_reports[0].path, local(&repo));
}

