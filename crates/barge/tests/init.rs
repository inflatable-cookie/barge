#[test]
fn init_refuses_a_symlinked_or_directory_local_file() {
    let fixture = Fixture::new();
    fixture.register();
    layout(&fixture);
    let repo = git_repo(&fixture, "repo");

    // A symlink is never written through or replaced.
    let real = fixture.temp.child("shared-scratch.md");
    fs::write(&real, "# Shared\n").unwrap();
    symlink(&real, local(&repo)).unwrap();
    let refused = fixture.barge.init(&repo, None).unwrap_err();
    assert_eq!(refused.kind(), ErrorKind::Refused);
    assert!(
        refused.message().contains("symlink"),
        "{}",
        refused.message()
    );
    assert_eq!(fs::read_to_string(&real).unwrap(), "# Shared\n");
    assert!(fs::symlink_metadata(local(&repo))
        .unwrap()
        .file_type()
        .is_symlink());
    assert!(fixture.barge.init_check(&repo, None).is_err());
    fs::remove_file(local(&repo)).unwrap();

    // A directory is not a file to replace.
    fs::create_dir(local(&repo)).unwrap();
    let refused = fixture.barge.init(&repo, None).unwrap_err();
    assert_eq!(refused.kind(), ErrorKind::Refused);
    assert!(
        refused.message().contains("directory"),
        "{}",
        refused.message()
    );
}

